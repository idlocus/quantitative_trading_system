# -*- coding: UTF-8 -*-
r"""生成 paper 运行计划任务的启动器 bat（部署模式对齐 pb-reader-be / blp-reader-be）

背景（2026-10-30 事故）：计划任务命令行直接写死
`.venv\Scripts\python.exe ...paper_day.py`——venv 基础解释器路径失效后
任务整体瘫痪且无人知晓。改为 build 生成启动器 bat，计划任务只指向 bat：

    - bat 内经 uv run 启动（uv 校验/自愈 .venv：缺失或损坏时按 uv.lock
      自动重建，不再依赖某个固定的解释器安装位置）
    - bat 是生成物（勿手改），重跑本脚本即可再生成；uv 路径在生成时
      探测并写死（计划任务的 PATH 快照可能不含 uv）

用法（项目根目录执行）:
    uv run python deploy/build_launchers.py           # 生成 bat + 打印注册命令
    uv run python deploy/build_launchers.py --check   # 自检（uv/目标脚本/bat 一致性）

生成物（项目根，入库可审计）:
    paper_day.bat        → scripts/paper_day.py     （每交易日 14:45）
    paper_watchdog.bat   → scripts/paper_watchdog.py（每交易日 16:00）

计划任务注册（管理员，一次性；命令也会在生成后打印）:
    schtasks /Create /TN "QuantPaperDay" /TR "D:\workspace\python_home\quant-project\paper_day.bat" /SC WEEKLY /D MON,TUE,WED,THU,FRI /ST 14:45 /F
    schtasks /Create /TN "QuantPaperWatchdog" /TR "D:\workspace\python_home\quant-project\paper_watchdog.bat" /SC WEEKLY /D MON,TUE,WED,THU,FRI /ST 16:00 /F
"""
import argparse
import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

# (bat 名, 目标脚本, 计划任务时刻) —— 新增任务在此登记
LAUNCHERS = [
    ('paper_day.bat', 'scripts/paper_day.py', '14:45'),
    ('paper_watchdog.bat', 'scripts/paper_watchdog.py', '16:00'),
]

# ASCII-only（bat 在 cmd 下按系统代码页解析，模板禁用非 ASCII 字符）
BAT_TEMPLATE = """@echo off
rem quant-project launcher - GENERATED by deploy/build_launchers.py, do not edit
rem Rerun the generator (uv run python deploy/build_launchers.py) to regenerate.
rem Runs via uv: .venv is validated/self-healed against uv.lock before start,
rem so a broken or missing venv no longer silently kills the task.
cd /d "{root}"
"{uv}" run python {script}
exit /b %ERRORLEVEL%
"""


def _find_uv() -> Path:
    """定位 uv.exe：PATH 优先，兜底常见安装位（对齐 pb-reader-be build_kit）"""
    found = shutil.which('uv')
    if found:
        return Path(found)
    for c in [Path.home() / '.local' / 'bin' / 'uv.exe',
              Path(Path.home(), 'AppData', 'Local', 'uv', 'uv.exe')]:
        if c.is_file():
            print('  uv 不在 PATH, 使用兜底位置: %s' % c)
            return c
    raise SystemExit('[缺少 uv] 未找到 uv.exe——计划任务无法启动，请先安装 uv')


def render_bat(uv_path: Path, script_rel: str) -> bytes:
    """渲染单个 bat 内容（CRLF + ASCII，cmd 代码页安全）"""
    body = BAT_TEMPLATE.format(root=PROJECT_ROOT, uv=uv_path, script=script_rel)
    return body.replace('\n', '\r\n').encode('ascii')


def build(uv_path: Path = None) -> int:
    uv_path = uv_path or _find_uv()
    if not uv_path.is_file():
        raise SystemExit('[uv 无效] %s 不存在' % uv_path)
    print('uv: %s' % uv_path)
    n = 0
    for bat_name, script_rel, clock in LAUNCHERS:
        target = PROJECT_ROOT / script_rel
        if not target.is_file():
            raise SystemExit('[缺少目标] %s 不存在' % target)
        out = PROJECT_ROOT / bat_name
        out.write_bytes(render_bat(uv_path, script_rel))
        print('  + %s -> %s (任务时刻 %s)' % (bat_name, script_rel, clock))
        n += 1
    print('\n注册计划任务（管理员执行一次）:')
    for bat_name, _s, clock in LAUNCHERS:
        tn = 'QuantPaperDay' if 'day' in bat_name else 'QuantPaperWatchdog'
        print(r'  schtasks /Create /TN "%s" /TR "%s" /SC WEEKLY /D MON,TUE,WED,THU,FRI /ST %s /F'
              % (tn, PROJECT_ROOT / bat_name, clock))
    return n


def check(uv_path: Path = None) -> int:
    """自检：uv 可用、目标脚本在、bat 与模板一致（未手改/未过期）"""
    uv_path = uv_path or _find_uv()
    problems = []
    for bat_name, script_rel, _clock in LAUNCHERS:
        out = PROJECT_ROOT / bat_name
        if not (PROJECT_ROOT / script_rel).is_file():
            problems.append('目标脚本缺失: %s' % script_rel)
            continue
        if not out.is_file():
            problems.append('未生成: %s（先运行 build）' % bat_name)
        elif out.read_bytes() != render_bat(uv_path, script_rel):
            problems.append('%s 与模板不一致（手改过或 uv 路径变化——重跑 build）' % bat_name)
    if problems:
        for p in problems:
            print('[FAIL] %s' % p)
        return 1
    print('自检通过：%d 个启动器与模板一致，uv=%s' % (len(LAUNCHERS), uv_path))
    return 0


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='只自检不生成')
    args = ap.parse_args()
    sys.exit(check() if args.check else 0 if build() else 1)
